#!/usr/bin/env node
// Precompiles the vendored receipt schema into a standalone validator module (ajv "standalone" code), so the SDK never
// generates code at runtime. Runtime `ajv.compile()` builds validators with `new Function`, which any page with a
// strict Content-Security-Policy (no 'unsafe-eval') blocks, and 0.1.1 did that at import time, so importing the SDK in
// such a page threw. The output is committed; `--check` fails when it no longer matches the schema.
//
// Builds one validator per vendored schema (receipt, change, pipeline).
//
//   node scripts/build-validator.mjs          # write src/generated/{receipt,change,pipeline}-validator.js
//   node scripts/build-validator.mjs --check  # exit 1 if any committed file is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const SCHEMAS = ["receipt", "change", "pipeline"];

// The one runtime helper ajv references is ucs2length (string length in code points). Inline it, so the module has no
// CommonJS require and no dependency on ajv at runtime. Same algorithm as ajv/dist/runtime/ucs2length.
const UCS2 = 'require("ajv/dist/runtime/ucs2length").default';
const inlined =
  "function ucs2length(str) { const len = str.length; let length = 0; let pos = 0; let value; while (pos < len) { " +
  "length++; value = str.charCodeAt(pos++); if (value >= 0xd800 && value <= 0xdbff && pos < len) { " +
  "value = str.charCodeAt(pos); if ((value & 0xfc00) === 0xdc00) pos++; } } return length; }";

// `uniqueItems` makes ajv reference its deep-equal helper (ajv/dist/runtime/equal, fast-deep-equal). Inline an
// equivalent for JSON data, for the same reason.
const EQUAL = 'require("ajv/dist/runtime/equal").default';
const equalFn =
  "function equal(a, b) { if (a === b) return true; if (a && b && typeof a == 'object' && typeof b == 'object') { " +
  "if (Array.isArray(a)) { if (!Array.isArray(b) || a.length !== b.length) return false; " +
  "for (let i = 0; i < a.length; i++) if (!equal(a[i], b[i])) return false; return true; } if (Array.isArray(b)) return false; " +
  "const ka = Object.keys(a); if (ka.length !== Object.keys(b).length) return false; " +
  "for (const k of ka) { if (!Object.prototype.hasOwnProperty.call(b, k) || !equal(a[k], b[k])) return false; } return true; } " +
  "return a !== a && b !== b; }";

function build(name) {
  const schemaPath = join(here, "..", "..", "..", "src", `${name}.schema.json`);
  const outPath = join(here, "..", "src", "generated", `${name}-validator.js`);
  const schemaText = readFileSync(schemaPath, "utf-8");
  // Formats need ajv-formats wired into the standalone output; none are used today, so refuse rather than silently
  // validate less than the Python checker does if one is ever added.
  if (/"format"\s*:/.test(schemaText)) {
    console.error(`build-validator: ${name}.schema.json uses \`format\`; wire ajv-formats into the standalone build first`);
    process.exit(1);
  }
  const ajv = new Ajv2020({ allErrors: false, strict: false, code: { source: true, esm: true } });
  let code = standaloneCode(ajv, ajv.compile(JSON.parse(schemaText)));
  if (code.includes(UCS2)) code = code.split(UCS2).join("ucs2length");
  const usesEqual = code.includes(EQUAL);
  if (usesEqual) code = code.split(EQUAL).join("equal");
  code = code.replace('"use strict";', `"use strict";${inlined}${usesEqual ? equalFn : ""}`);

  if (/\brequire\(/.test(code)) {
    console.error(`build-validator: the ${name} validator still requires a runtime module:`, code.match(/require\([^)]*\)/)[0]);
    process.exit(1);
  }
  if (/new Function|\bFunction\(|\beval\(/.test(code)) {
    console.error(`build-validator: the ${name} validator evaluates code at runtime`);
    process.exit(1);
  }
  const out =
    `// @ts-nocheck\n/* eslint-disable */\n// Generated by scripts/build-validator.mjs from ../../../src/${name}.schema.json. Do not edit by hand.\n` +
    `${code}\n`;
  return { outPath, out, name };
}

const check = process.argv.includes("--check");
let stale = false;
for (const name of SCHEMAS) {
  const { outPath, out } = build(name);
  if (check) {
    let current = "";
    try {
      current = readFileSync(outPath, "utf-8");
    } catch {}
    if (current !== out) {
      console.error(`build-validator: src/generated/${name}-validator.js is stale; run \`npm run build:validator\``);
      stale = true;
    }
  } else {
    writeFileSync(outPath, out);
    console.log(`build-validator: wrote ${outPath} (${out.length} bytes)`);
  }
}
if (check) {
  if (stale) process.exit(1);
  console.log("build-validator: up to date");
}
